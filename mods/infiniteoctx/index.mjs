import { readFile } from "node:fs/promises"

// Anchor checks fail closed on incompatible upstream revisions.
function replace(source, before, after, label) {
  if (source.includes(after)) throw new Error(`infiniteoctx: already applied (${label})`)
  if (source.split(before).length !== 2) throw new Error(`infiniteoctx: expected one source anchor: ${label}`)
  return source.replace(before, () => after)
}

const file = (name) => readFile(new URL(`./${name}`, import.meta.url), "utf8")
const POLICY_KEYS = ["keepSteps", "minChars", "batchTokens"]

/** The paging policy: the defaults, overridden by options.infiniteoctx in infiniteoc.json. */
export function policySource(options = {}) {
  const custom = options?.infiniteoctx ?? {}
  const entries = POLICY_KEYS.flatMap((key) => {
    if (custom[key] === undefined) return []
    if (!Number.isInteger(custom[key]) || custom[key] < 0) throw new Error(`infiniteoctx: options.infiniteoctx.${key} must be a non-negative integer`)
    return [`${key}: ${custom[key]}`]
  })
  return `// Generated by mods/infiniteoctx from options.infiniteoctx in infiniteoc.json.
import { DEFAULT_POLICY, type Policy } from "./infiniteoctx-lib.js"

export const POLICY: Policy = { ...DEFAULT_POLICY${entries.length ? `, ${entries.join(", ")}` : ""} }
`
}

// After upstream's write tool and mods/infinitokensave (paging must see its duplicate references, not
// the duplicates), before mods/ctx-context's request snapshot: /context then shows the request as sent.
const TOKENSAVE = "  InfiniteocTokensave.Plugin,\n"
export function internalSource(source) {
  source = replace(source, 'import { WarmingPlugin } from "./warming.js"', 'import * as InfiniteocOctx from "./infiniteoctx.js"\nimport { WarmingPlugin } from "./warming.js"', "warming import")
  const after = source.includes(`  WriteTool.Plugin,\n${TOKENSAVE}`) ? `  WriteTool.Plugin,\n${TOKENSAVE}` : "  WriteTool.Plugin,\n"
  return replace(source, after, `${after}  InfiniteocOctx.Plugin,\n`, "plugin list")
}

export default {
  id: "infiniteoctx",
  version: "1.0.0",
  async setup(api) {
    if (api.options?.infiniteoctx?.enabled === false) return
    const store = await file("store.ts")
    await api.write("packages/core/src/plugin/infiniteoctx-lib.ts", await file("lib.ts"))
    await api.write("packages/core/src/plugin/infiniteoctx-store.ts", store)
    await api.write("packages/core/src/plugin/infiniteoctx-config.ts", policySource(api.options))
    await api.write("packages/core/src/plugin/infiniteoctx.ts", await file("plugin.ts"))
    await api.patch("packages/core/src/plugin/internal.ts", internalSource)
    await api.write("packages/tui/src/infiniteoc-features/octx-store.ts", store)
    api.tui.command({ id: "octx", title: "Context paging (InfiniteOCTX)", slash: "octx", category: "Context", source: await file("tui/octx.tsx") })
  },
}
